import '../support/isolation.js';
import {test,expect,type Page} from '@playwright/test';
import {readFile,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import pg from 'pg';
import {secret} from '../../packages/config/src/index.js';
type Fixture={t116Cookie:string;foreignCookie:string;reviewerCookie:string;t116TaskId:string;t116RunId:string;t116ExpectedValue:string;t116TenantId:string;isolatedDatabase:string;approvalTaskId:string;approvalRunId:string;approvalActionId:string;approvalId:string;approvalCapability:string;approvalGoal:string};
const fixture=async(project:string)=>JSON.parse(await readFile('.data/test-environment/browser-artifacts.json','utf8'))[project] as Fixture;
const area=(page:Page)=>page.getByRole('region',{name:'任务成果',exact:true}),ledger=(page:Page)=>page.getByRole('complementary',{name:'动作账本',exact:true});
test.setTimeout(60000);
async function useSession(page:Page,cookie:string){await page.context().clearCookies();await page.context().addCookies([{name:'oa_session',value:cookie,url:'http://localhost:64702'}]);}
async function noOverflow(page:Page){expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);}
test('T116 desktop and mobile show task, approval and artifact with operable buttons, consistent states and a denied foreign deep link',async({page},info)=>{
 const f=await fixture(info.project.name),evidence='reports/t116-workbench-20261023/screenshots';
 await mkdir(evidence,{recursive:true});
 await useSession(page,f.t116Cookie);
 await page.goto('/tasks?task='+f.t116TaskId);
 await expect(page.getByText('工作台已就绪',{exact:true})).toBeVisible();
 await expect(page.getByRole('heading',{name:'Read the exact synthetic value'})).toBeVisible();
 const panel=area(page);
 await expect(panel.getByRole('button',{name:'生成受保护成果',exact:true})).toBeEnabled();
 await panel.getByLabel('成果格式',{exact:true}).selectOption('txt');
 await panel.getByRole('button',{name:'生成受保护成果',exact:true}).click();
 await expect(panel.getByRole('article')).toHaveCount(1);
 await expect(panel.getByRole('button',{name:'受保护下载',exact:true})).toBeEnabled();
 const saved=page.waitForEvent('download');
 await panel.getByRole('button',{name:'受保护下载',exact:true}).click();
 const download=await saved,path=await download.path();
 expect(path).toBeTruthy();
 const bytes=await readFile(path!),sha=createHash('sha256').update(bytes).digest('hex');
 expect(bytes.toString()).toContain(f.t116ExpectedValue);
 await expect(panel.getByRole('article').locator('code')).toHaveText('SHA-256 '+sha);
 await panel.screenshot({path:evidence+'/'+info.project.name+'-artifact.png'});
 await noOverflow(page);
 await page.goto('/tasks?task='+f.approvalTaskId);
 await expect(page.getByRole('heading',{name:f.approvalGoal})).toBeVisible();
 const requester=ledger(page);
 await expect(requester).toContainText(f.approvalCapability);
 await expect(requester).toContainText('需要申请审批');
 await expect(requester).toContainText('等待审批人决定');
 await expect(requester).toContainText('合成审批演示');
 await expect(requester).not.toContainText('T116_PRIVATE_INPUT_SENTINEL');
 await expect(requester.getByRole('button',{name:'批准此动作',exact:true})).toHaveCount(0);
 await noOverflow(page);
 await useSession(page,f.reviewerCookie);
 await page.goto('/tasks');
 await expect(page.getByRole('heading',{name:'待我审批'})).toBeVisible();
 const view=page.getByRole('button',{name:'查看审批 '+f.approvalCapability,exact:true});
 await expect(view).toBeEnabled();
 await view.click();
 const preview=page.getByRole('article',{name:'审批预览'});
 await expect(preview).toContainText('合成审批演示');
 await expect(preview).toContainText('隔离任务');
 await expect(preview).not.toContainText('T116_PRIVATE_INPUT_SENTINEL');
 await preview.screenshot({path:evidence+'/'+info.project.name+'-approval-preview.png'});
 const approve=preview.getByRole('button',{name:'批准此动作',exact:true});
 await expect(approve).toBeEnabled();
 await approve.click();
 await expect(page.getByText('已批准，尚未执行。系统将按当前权限恢复原任务。',{exact:true})).toBeVisible();
 await expect(page.getByText('暂无待审批动作。',{exact:true})).toBeVisible();
 await noOverflow(page);
 await useSession(page,f.t116Cookie);
 await page.goto('/tasks?task='+f.approvalTaskId);
 await expect(page.getByRole('heading',{name:f.approvalGoal})).toBeVisible();
 const approved=ledger(page);
 await expect(approved).toContainText('已批准，尚未执行');
 await expect(approved).not.toContainText('等待审批人决定');
 await expect(approved).not.toContainText('执行结果已核验');
 await expect(approved.getByRole('button',{name:'批准此动作',exact:true})).toHaveCount(0);
 await approved.screenshot({path:evidence+'/'+info.project.name+'-approved-ledger.png'});
 await noOverflow(page);
 const url=new URL(secret('MIGRATION_DATABASE_URL')!);
 expect(url.hostname).toBe('127.0.0.1');
 expect(url.port).toBe('64711');
 expect(f.isolatedDatabase).toMatch(/^anthys_test_group_reminder_[a-f0-9]{32}$/);
 url.pathname='/'+f.isolatedDatabase;
 const db=new pg.Pool({connectionString:url.href,max:1,connectionTimeoutMillis:3000,query_timeout:12000});
 try{
  const writes=(await db.query("SELECT count(*)::int n FROM outbox WHERE tenant_id=$1 AND kind='SYNTHETIC_T116_WRITE'",[f.t116TenantId])).rows[0].n;
  const action=(await db.query('SELECT state FROM tool_actions WHERE id=$1',[f.approvalActionId])).rows[0].state;
  const approval=(await db.query('SELECT state FROM approvals WHERE id=$1',[f.approvalId])).rows[0].state;
  const run=(await db.query('SELECT status,resume_action_id FROM runs WHERE id=$1',[f.approvalRunId])).rows[0];
  expect(writes).toBe(0);
  expect(action).toBe('APPROVED');
  expect(approval).toBe('APPROVED');
  expect(run).toMatchObject({status:'QUEUED',resume_action_id:f.approvalActionId});
 }finally{await db.end();}
 await useSession(page,f.foreignCookie);
 const denied=await page.request.get('/api/v1/tasks/'+f.approvalTaskId);
 expect(denied.status()).toBe(404);
 await page.goto('/tasks?task='+f.approvalTaskId);
 await expect(page.getByRole('status').first()).toContainText('登录');
 await expect(page.getByText(f.approvalGoal,{exact:true})).toHaveCount(0);
 await expect(page.getByText('动作账本',{exact:true})).toHaveCount(0);
 await noOverflow(page);
 await page.screenshot({path:evidence+'/'+info.project.name+'-foreign-denied.png'});
});
